import asyncio
import json
import time


# ---------------------------------------------------------------------------
# THE ENTIRE APP: one async callable with three arguments.
# uvicorn calls this once per connection (and once at boot for lifespan).
# ---------------------------------------------------------------------------
async def app(scope, receive, send):
    if scope["type"] == "lifespan":
        await handle_lifespan(scope, receive, send)
    elif scope["type"] == "http":
        await handle_http(scope, receive, send)


# ---------------------------------------------------------------------------
# LIFESPAN: one call, lives for the whole process.
# ---------------------------------------------------------------------------
async def handle_lifespan(scope, receive, send):
    state = scope["state"]  # shallow-copied into every connection's scope

    while True:
        message = await receive()

        if message["type"] == "lifespan.startup":
            print("[lifespan] startup - loading resources")
            state["started_at"] = time.time()
            state["fake_model"] = {"name": "fake-embedder"}
            await send({"type": "lifespan.startup.complete"})
            # raise here instead, and uvicorn refuses to serve:
            # await send({"type": "lifespan.startup.failed", "message": "boom"})
            print("[lifespan] startup - await returned")

        elif message["type"] == "lifespan.shutdown":
            print("[lifespan] shutdown - releasing resources")
            await send({"type": "lifespan.shutdown.complete"})
            print("[lifespan] shutdown - await returned")
            return


# ---------------------------------------------------------------------------
# HTTP: routing by hand, since ASGI has no routing.
# ---------------------------------------------------------------------------
async def handle_http(scope, receive, send):
    path = scope["path"]

    if path == "/":
        await respond(send, b"hello from raw ASGI\n")

    elif path == "/scope":
        # everything uvicorn knows about this connection
        body = json.dumps(readable(scope), indent=2).encode()
        await respond(send, body, content_type=b"application/json")

    elif path == "/echo":
        body = await read_body(receive)
        await respond(send, f"received {len(body)} bytes\n".encode())

    elif path == "/stream":
        await stream_tokens(receive, send)

    elif path == "/block":
        time.sleep(5)  # THE TRAP: freezes the loop, every request waits
        await respond(send, b"blocked the event loop for 5s\n")

    elif path == "/sleep":
        await asyncio.sleep(5)  # yields: other requests keep being served
        await respond(send, b"awaited 5s, loop stayed free\n")

    else:
        await respond(send, b"not found\n", status=404)


# ---------------------------------------------------------------------------
# send: one message to open the response, one or more for the body
# ---------------------------------------------------------------------------
async def respond(send, body, content_type=b"text/plain", status=200):
    await send({
        "type": "http.response.start",
        "status": status,
        "headers": [
            (b"content-type", content_type),
            (b"content-length", str(len(body)).encode()),
        ],
    })
    await send({"type": "http.response.body", "body": body})
    # more_body defaults to False -> response complete


# ---------------------------------------------------------------------------
# receive: one await, one message. Loop until more_body is False.
# ---------------------------------------------------------------------------
async def read_body(receive):
    chunks = []
    while True:
        message = await receive()
        print(f"[read_body] - receive returned await {message}")

        if message["type"] == "http.request":
            chunks.append(message.get("body", b""))
            if not message.get("more_body", False):
                break

        elif message["type"] == "http.disconnect":
            print("[echo] client dropped mid-body")
            break

    return b"".join(chunks)


# ---------------------------------------------------------------------------
# Streaming: send called repeatedly, with disconnect handling.
# This is what StreamingResponse does for you.
# ---------------------------------------------------------------------------
async def stream_tokens(receive, send):
    await send({
        "type": "http.response.start",
        "status": 200,
        "headers": [(b"content-type", b"text/plain")],
    })

    gone = asyncio.Event()

    async def watch_for_disconnect():
        while True:
            message = await receive()
            if message["type"] == "http.disconnect":
                gone.set()
                return

    watcher = asyncio.create_task(watch_for_disconnect())

    try:
        for i in range(1, 11):
            if gone.is_set():
                print(f"[stream] client left, stopping at token {i}")
                return  # in real life: stop paying for LLM tokens here

            await send({
                "type": "http.response.body",
                "body": f"token {i}\n".encode(),
                "more_body": True,
            })
            await asyncio.sleep(0.5)

        await send({"type": "http.response.body", "body": b"", "more_body": False})
    finally:
        watcher.cancel()


# ---------------------------------------------------------------------------
# scope contains bytes and tuples, so make it printable
# ---------------------------------------------------------------------------
def readable(scope):
    out = {}
    for key, value in scope.items():
        if key == "headers":
            out[key] = [[k.decode(), v.decode()] for k, v in value]
        elif key in ("client", "server"):
            out[key] = list(value) if value else None
        elif isinstance(value, bytes):
            out[key] = value.decode()
        elif isinstance(value, dict):
            out[key] = {k: str(v) for k, v in value.items()}
        elif isinstance(value, (str, int, float, bool, type(None), list)):
            out[key] = value
        else:
            out[key] = str(value)
    return out